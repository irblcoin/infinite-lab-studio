// Encode the rendered loop WAVs to MP3 and generate the loop catalogue.
// Run after scripts/make-loops.py:
//   node scripts/encode-loops.mjs
import { readFileSync, writeFileSync, mkdirSync, statSync, readdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import lamejs from '@breezystack/lamejs'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const src = '/tmp/loops'
const outDir = join(root, 'public', 'packs', 'loops')
mkdirSync(outDir, { recursive: true })

const meta = JSON.parse(readFileSync(join(src, 'meta.json'), 'utf8'))

function readWav(path) {
  const buf = readFileSync(path)
  let offset = 12
  let fmt = null
  let data = null
  while (offset < buf.length - 8) {
    const id = buf.toString('ascii', offset, offset + 4)
    const size = buf.readUInt32LE(offset + 4)
    if (id === 'fmt ') fmt = { channels: buf.readUInt16LE(offset + 10), rate: buf.readUInt32LE(offset + 12), bits: buf.readUInt16LE(offset + 22) }
    if (id === 'data') { data = buf.subarray(offset + 8, offset + 8 + size); break }
    offset += 8 + size + (size % 2)
  }
  if (!fmt || !data) throw new Error('bad wav ' + path)
  const frames = data.length / (fmt.channels * (fmt.bits / 8))
  const left = new Int16Array(frames)
  const right = new Int16Array(frames)
  for (let i = 0; i < frames; i++) {
    left[i] = data.readInt16LE(i * 4)
    right[i] = data.readInt16LE(i * 4 + 2)
  }
  return { left, right, sampleRate: fmt.rate, frames }
}

let total = 0
const files = []
for (const loop of meta) {
  const wav = readWav(join(src, `${loop.id}.wav`))
  const enc = new lamejs.Mp3Encoder(2, wav.sampleRate, 128)
  const chunks = []
  const block = 1152
  for (let i = 0; i < wav.frames; i += block) {
    const l = wav.left.subarray(i, i + block)
    const r = wav.right.subarray(i, i + block)
    const mp3 = enc.encodeBuffer(l, r)
    if (mp3.length) chunks.push(Buffer.from(mp3))
  }
  const tail = enc.flush()
  if (tail.length) chunks.push(Buffer.from(tail))
  const out = Buffer.concat(chunks)
  const path = join(outDir, `${loop.id}.mp3`)
  writeFileSync(path, out)
  total += out.length
  files.push({ path: `${loop.id}.mp3`, bytes: out.length })
  loop.bytes = out.length
}

// The loop catalogue the app imports at build time.
const ts = `// GENERATED by scripts/encode-loops.mjs — do not edit by hand.
export interface LoopDef {
  id: string
  name: string
  genre: string
  genreLabel: string
  role: string
  bpm: number
  key: string
  bars: number
  beats: number
  duration: number
  file: string
}

export const LOOPS: LoopDef[] = ${JSON.stringify(meta, null, 1)}

export const LOOP_GENRES = [...new Set(LOOPS.map((l) => l.genreLabel))]
`
writeFileSync(join(root, 'src', 'data', 'loops.ts'), ts)

// Merge into the pack catalogue so the installer and credits page see it.
const indexPath = join(root, 'public', 'packs', 'index.json')
const catalog = JSON.parse(readFileSync(indexPath, 'utf8'))
const pack = {
  id: 'loops',
  name: 'Real Loops',
  author: 'ILS loop lab from CC0/CC-BY recordings',
  license: 'CC0 1.0 / CC BY 3.0',
  licenseUrl: 'https://creativecommons.org/publicdomain/zero/1.0/',
  source: 'https://github.com/tidalcycles/Dirt-Samples',
  description: '56 loops across hip hop, trap, R&B, pop, dream pop, EDM, rock and lo-fi, sequenced from real recordings. Each is tagged with its tempo and key and time-stretches to the project tempo.',
  category: 'Loops',
  loops: meta,
  instruments: [],
  files,
  bytes: total,
}
catalog.packs = [...catalog.packs.filter((p) => p.id !== 'loops'), pack]
writeFileSync(indexPath, JSON.stringify(catalog, null, 1))

console.log(`encoded ${meta.length} loops, ${(total / 1e6).toFixed(1)} MB`)
console.log('folder bytes', readdirSync(outDir).length, 'files')
